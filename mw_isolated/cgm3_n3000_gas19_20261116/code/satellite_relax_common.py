VERSION = "tg19-independent-relax-v1"
KPC_CM = 3.0856775814913673e21
MSUN_G = 1.989e33  # matches the user's GIZMO unit convention
GYR_S = 365.25 * 86400.0 * 1e9
UNIT_KEYS = ("UnitLength_in_cm", "UnitMass_in_g", "UnitVelocity_in_cm_per_s")
DEFAULT_UNITS = (3.08568e21, 1.989e43, 1e5)
OFFSETS = ("LMC_SHOOTING_POSITION_OFFSET_kpc", "LMC_SHOOTING_VELOCITY_OFFSET_km_s",
           "SMC_SHOOTING_POSITION_OFFSET_kpc", "SMC_SHOOTING_VELOCITY_OFFSET_km_s")
ID_FIELDS = ("ParticleIDs", "ParticleChildIDsNumber", "ParticleIDGenerationNumber")


def fail(message):
    raise ValueError(message)


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def plain(value):
    if isinstance(value, dict):
        return {str(k): plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain(v) for v in value]
    if isinstance(value, np.ndarray):
        return plain(value.tolist())
    if isinstance(value, np.generic):
        return plain(value.item())
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    if isinstance(value, Path):
        return str(value)
    return value


def write_json(path, value):
    Path(path).write_text(json.dumps(plain(value), ensure_ascii=False, indent=2,
                                    allow_nan=False) + "\n", encoding="utf-8")


def read_param(path):
    path = Path(path).expanduser().resolve(strict=True)
    lines = path.read_text(encoding="utf-8").splitlines()
    values = {}
    for line in lines:
        text = re.split(r"[#%]", line, maxsplit=1)[0].strip()
        if not text:
            continue
        fields = text.split()
        if len(fields) < 2:
            fail(f"参数行缺少值: {line}")
        if fields[0] in values:
            fail(f"参数重复: {fields[0]}")
        values[fields[0]] = fields[1]
    return path, lines, values


def write_param(path, lines, overrides):
    for key, value in overrides.items():
        if any(char.isspace() for char in str(value)):
            fail(f"GIZMO 参数值不能包含空白字符: {key}={value!r}")
    remaining = dict(overrides)
    output = ["% Generated by " + VERSION]
    for line in lines:
        text = re.split(r"[#%]", line, maxsplit=1)[0].strip()
        key = text.split()[0] if text else None
        if key in remaining:
            output.append(f"{key:<42} {remaining.pop(key)}")
        else:
            output.append(line)
    for key, value in remaining.items():
        output.append(f"{key:<42} {value}")
    Path(path).write_text("\n".join(output) + "\n", encoding="utf-8")


def param_units(values):
    missing = set(UNIT_KEYS) - values.keys()
    if missing:
        fail(f"base-param 必须明确给出单位: {sorted(missing)}")
    raw = np.array([float(values[k]) for k in UNIT_KEYS])
    if not np.allclose(raw, DEFAULT_UNITS, rtol=1e-5, atol=0):
        fail("本套脚本限定原模型单位 kpc / 1e10 Msun / km s^-1；请勿混用其他单位。")
    if float(values.get("ComovingIntegrationOn", 0)) != 0:
        fail("仅支持非宇宙学；HubbleParam 不用于非宇宙学单位缩放。")
    return dict(zip(UNIT_KEYS, raw)), dict(length_kpc=raw[0]/KPC_CM,
        mass_msun=raw[1]/MSUN_G, velocity_kms=raw[2]/1e5,
        time_gyr=raw[0]/raw[2]/GYR_S)


def check_agn_off(values):
    for key in ("BlackHoleAccretionFactor", "BlackHoleEddingtonFactor", "BlackHoleFeedbackFactor"):
        if float(values.get(key, 0)) != 0:
            fail(f"本阶段应关闭 AGN: {key} 必须为 0。")


def executable_info(path):
    path = Path(path).expanduser().resolve(strict=True)
    if not path.is_file() or not os.access(path, os.X_OK):
        fail(f"GIZMO 路径不是可执行文件: {path}")
    return {"path": str(path), "sha256": sha256(path)}


def run_script(path, executable, param, working_dir, flag, log, mpi_tasks):
    # Running in the base parameter directory preserves relative cooling-table paths.
    quote = shlex.quote
    text = f'''#!/usr/bin/env bash
set -euo pipefail
cd {quote(str(working_dir))}
GIZMO_BIN={quote(str(executable['path']))}
EXPECTED_SHA={quote(executable['sha256'])}
ACTUAL_SHA=$(sha256sum "$GIZMO_BIN" | cut -d' ' -f1)
if [[ "$ACTUAL_SHA" != "$EXPECTED_SHA" ]]; then
  echo "GIZMO binary changed after IC creation; use the same build for all three systems." >&2
  exit 2
fi
if compgen -G {quote(str(Path(log).parent / 'output' / 'snapshot*'))} > /dev/null; then
  echo "Output already contains snapshots. Refusing an accidental repeated run." >&2
  exit 2
fi
mpirun -np "${{NPROC:-{mpi_tasks}}}" nice -n 19 "$GIZMO_BIN" {quote(str(param))} {flag} 2>&1 | tee {quote(str(log))}
'''
    Path(path).write_text(text, encoding="utf-8")
    Path(path).chmod(0o755)


def header_attrs(counts, box, time, raw_units):
    counts = np.asarray(counts, dtype=np.uint64)
    if counts.shape != (6,) or np.any(counts > np.iinfo(np.uint32).max):
        fail("Single-file counts exceed uint32; split output is required")
    return dict(NumPart_ThisFile=counts.astype(np.uint32),
        NumPart_Total=(counts & np.uint64(0xffffffff)).astype(np.uint32),
        NumPart_Total_HighWord=(counts >> np.uint64(32)).astype(np.uint32),
        MassTable=np.zeros(6), Time=float(time), Redshift=0., BoxSize=float(box),
        NumFilesPerSnapshot=1, Omega0=0., OmegaLambda=0., HubbleParam=1.,
        Flag_Sfr=1, Flag_Feedback=1, Flag_Cooling=1, Flag_StellarAge=1,
        Flag_Metals=11, Flag_DoublePrecision=1, Flag_IC_Info=0, **raw_units)


def particle_keys(group):
    arrays = []
    for key in ID_FIELDS:
        if key not in group:
            fail(f"缺少 {key}；flag2 输入需要完整粒子身份字段。")
        value = np.asarray(group[key])
        if value.ndim != 1 or value.dtype.kind not in "ui":
            fail(f"{key} 必须是一维整数数组。")
        arrays.append(value.astype(np.uint64))
    result = np.rec.fromarrays(arrays, names="id,child,generation")
    if len(np.unique(result)) != len(result):
        fail("同一 PartType 内 (ID,child,generation) 重复，无法安全追踪。")
    return result


def read_snapshot(path, raw_units):
    path = Path(path).expanduser().resolve(strict=True)
    with h5py.File(path, "r") as f:
        attrs = dict(f["Header"].attrs)
        if int(attrs.get("NumFilesPerSnapshot", 1)) != 1:
            fail(f"暂不支持分文件快照: {path}")
        actual_units, provenance = resolve_units(f, fallback=raw_units)
        require_noncosmological(f)
        unit_missing = [key for key, source in provenance.items() if "fallback" in source]
        for key,wanted in raw_units.items():
            if not np.isclose(actual_units[key], wanted, rtol=1e-10, atol=0):
                fail(f"{path}: 单位 {key} differs from base-param; explicit physical conversion is required")
        config = plain(dict(f["Config"].attrs)) if "Config" in f else {}
        if "Parameters" in f and float(f["Parameters"].attrs.get("ComovingIntegrationOn", 0)) != 0:
            fail("不支持宇宙学快照。")
        for key in config:
            if key.startswith(("MAGNETIC", "COSMIC_RAY", "RT_", "CHIMES", "BH_WIND", "BH_DEBUG_FIX")) or key in (
                    "GALSF_EFFECTIVE_EQS", "ASSIGN_NEW_IDS", "NO_CHILD_IDS_IN_ICS"):
                fail(f"当前合并器未支持/不适用该编译配置: {key}")
        parts, field_attrs, group_attrs = {}, {}, {}
        counts = np.asarray(attrs["NumPart_ThisFile"], dtype=int)
        total = np.asarray(attrs.get("NumPart_Total", counts), dtype=np.uint64)
        total += np.asarray(attrs.get("NumPart_Total_HighWord", np.zeros(6)), dtype=np.uint64) << np.uint64(32)
        if not np.array_equal(counts, total):
            fail(f"{path}: 单文件粒子数与总数不一致。")
        for p in range(6):
            name = f"PartType{p}"
            if counts[p] == 0:
                continue
            if name not in f:
                fail(f"{path}: 缺少 {name}")
            parts[p], field_attrs[p], group_attrs[p] = {}, {}, dict(f[name].attrs)
            for key, ds in f[name].items():
                if not isinstance(ds, h5py.Dataset) or ds.ndim == 0 or len(ds) != counts[p]:
                    fail(f"{path}/{name}/{key}: 非粒子数据集，需人工定义合并规则。")
                value = ds[...]
                if value.dtype.kind in "fc" and not np.all(np.isfinite(value)):
                    fail(f"{path}/{name}/{key} 有 NaN/Inf")
                parts[p][key] = value
                field_attrs[p][key] = dict(ds.attrs)
            parts[p] = normalize_fields(parts[p], target="c")
            for old,new in FIELD_ALIASES.items():
                if new in field_attrs[p]:
                    field_attrs[p].setdefault(old, field_attrs[p][new])
                    del field_attrs[p][new]
            g = parts[p]
            if "Masses" not in g:
                mass = float(attrs["MassTable"][p])
                if mass <= 0:
                    fail(f"{name} 无有效质量。")
                g["Masses"] = np.full(counts[p], mass)
            for key in ("Coordinates", "Velocities"):
                if key not in g or g[key].shape != (counts[p], 3):
                    fail(f"{name}/{key} 必须为 N×3。")
            if np.any(g["Masses"] <= 0):
                fail(f"{name}: 质量必须为正。")
            particle_keys(g)
            if p in (0, 4):
                if "Metallicity" not in g or g["Metallicity"].shape != (counts[p], 11):
                    fail(f"{name}: 本项目需要 N×11 Metallicity，不能猜补元素。")
                z = g["Metallicity"]
                if np.any(z < 0) or np.any(z[:, 0] + z[:, 1] > 1 + 1e-6):
                    fail(f"{name}: 非法金属/氦质量分数。")
            if p == 4 and "StellarFormationTime" not in g:
                fail("恒星缺少 StellarFormationTime。")
            if p == 0:
                for key in ("InternalEnergy", "Density", "SmoothingLength", "ElectronAbundance"):
                    if key not in g:
                        fail(f"气体缺少 {key}；请使用真实演化输出，不能用原始 flag0 IC 代替。")
                for key in ("InternalEnergy", "Density", "SmoothingLength"):
                    if np.any(g[key] <= 0):
                        fail(f"气体 {key} 必须为正。")
        if not {0, 1, 4}.issubset(parts):
            fail(f"{path}: 需要 PartType0、1、4。")
    return dict(path=path, header=attrs, parts=parts, field_attrs=field_attrs,
                group_attrs=group_attrs, config=config, missing_units=unit_missing)


def generator_main(system):
    parser = argparse.ArgumentParser(description=f"生成 {system} TG19 独立弛豫 IC、param 和 flag0 启动脚本")
    parser.add_argument("--target-format", choices=("c","cpp"), default="c", help="Output naming only; compiled flag0 initialization still applies")
    parser.add_argument("--base-param", required=True, help="实际 MW 参数文件；继承冷却、恒星形成等参数")
    parser.add_argument("--gizmo-executable", required=True)
    parser.add_argument("--run-dir", default="lmcre" if system == "LMC" else "smcre")
    times = parser.add_mutually_exclusive_group()
    times.add_argument("--relax-gyr", type=float, help="物理 Gyr；默认 0.6136")
    times.add_argument("--relax-code", type=float, help="直接指定代码时间，例如 0.6136 约等于 0.6 Gyr")
    parser.add_argument("--metallicity", type=float, default=.2 if system == "LMC" else .1, help="InitMetallicity，单位 Zsun")
    parser.add_argument("--stellar-age-gyr", type=float, help="InitStellarAge 的均值；继承 base-param，否则显式采用原代码默认 10 Gyr")
    parser.add_argument("--gas-particle-mass", type=float, default=1e5)
    parser.add_argument("--gas-total-mass", type=float, required=True)
    parser.add_argument("--dm-particle-mass", type=float, default=1e6)
    parser.add_argument("--star-particle-mass", type=float, default=1e5)
    parser.add_argument("--seed", type=int, default=27191 if system == "LMC" else 27192)
    parser.add_argument("--id-bits", type=int, choices=(32, 64), default=32, help="与 GIZMO LONGIDS 编译设置一致")
    parser.add_argument("--mpi-tasks", type=int, default=6)
    args = parser.parse_args()
    base, lines, values = read_param(args.base_param)
    raw_units, units = param_units(values)
    check_agn_off(values)
    executable = executable_info(args.gizmo_executable)
    end_code = args.relax_code if args.relax_code is not None else (
        (.6136 if args.relax_gyr is None else args.relax_gyr) / units["time_gyr"])
    age = args.stellar_age_gyr if args.stellar_age_gyr is not None else float(values.get("InitStellarAge", 10.))
    if not np.isfinite(end_code) or end_code <= 0 or not np.isfinite(age) or age < 0:
        fail("弛豫时长必须为正，恒星平均年龄必须非负且有限。")
    if args.metallicity < 0 or args.metallicity > 10 or not np.isfinite(args.metallicity):
        fail("metallicity 必须在 [0,10] Zsun。")
    for mass in (args.gas_particle_mass, args.dm_particle_mass, args.star_particle_mass):
        if not np.isfinite(mass) or mass <= 0:
            fail("粒子质量必须为正且有限。")
    run = Path(args.run_dir).expanduser().resolve()
    if run.exists() and (not run.is_dir() or any(run.iterdir())):
        fail(f"拒绝覆盖非空弛豫目录: {run}")
    sat = backend.build_default_satellites(lmc_cgm_core_radius=1.,lmc_cgm_mode="truncated",
              lmc_cgm_rmax=50.,v1_gas_truncation_in_a=5.,satellite_structure_model="tg19-oprea-no-binary",
              satellite_gas_model="tg19-extended-disks")[0 if system == "LMC" else 1]
    if not np.isfinite(args.gas_total_mass) or args.gas_total_mass <= 0:
        fail("Requested gas mass must be finite and positive.")
    sat = replace(sat, cgm_metallicity_zsun=args.metallicity, cgm_mass_rmax=args.gas_total_mass)
    rng = np.random.default_rng(args.seed)
    sampled = backend.make_satellite_particles(rng, sat, np.zeros(3), np.zeros(3),
        args.dm_particle_mass, args.star_particle_mass, args.gas_particle_mass)
    box = float(values.get("BoxSize", 1000))
    if box * units["length_kpc"] < 4 * sat.dm_rmax:
        fail("BoxSize 太小，需至少容纳四倍暗晕截断半径。")
    run.mkdir(parents=True, exist_ok=True)
    (run / "output").mkdir()
    ic = run / f"{system.lower()}_ic.hdf5"
    counts = np.zeros(6, dtype=int)
    id_dtype = np.uint32 if args.id_bits == 32 else np.uint64
    with h5py.File(ic, "x") as f:
        for p, component in ((0, "gas"), (1, "dm"), (4, "star")):
            n = len(sampled[component + "_mass"])
            if n >= backend.ID_BLOCK_SIZE:
                fail("粒子数超出组件预留 ID 区间。")
            counts[p] = n
            g = f.create_group(f"PartType{p}")
            start = int(getattr(backend, f"{system}_{component.upper()}_ID_START"))
            data = dict(Coordinates=sampled[component + "_pos"]/units["length_kpc"] + box/2,
                Velocities=sampled[component + "_vel"]/units["velocity_kms"],
                Masses=sampled[component + "_mass"]/units["mass_msun"],
                ParticleIDs=checked_ids(np.arange(start, start+n, dtype=np.uint64),args.id_bits),
                ParticleChildIDsNumber=np.zeros(n, dtype=np.uint32),
                ParticleIDGenerationNumber=np.zeros(n, dtype=np.uint32))
            if p in (0, 4):
                data["Metallicity"] = np.tile(backend.stellar_metallicity_vector(args.metallicity), (n, 1))
            if p == 0:
                data["InternalEnergy"] = sampled["gas_u"] / units["velocity_kms"]**2
            if p == 4:
                # flag0 deliberately initializes this again using GIZMO's own RNG.
                data["StellarFormationTime"] = -rng.uniform(0, 2*age, n) / units["time_gyr"]
            for key, value in data.items():
                g.create_dataset(key, data=value)
        header = f.create_group("Header")
        header.attrs.update(header_attrs(counts, box, 0, raw_units))
        meta = f.create_group("IndependentRelaxationReference")
        meta.attrs.update(SYSTEM=system, VERSION=VERSION, BINARY_PRE_EVOLUTION_INCLUDED=0,
            TARGET_END_CODE=end_code, TARGET_END_GYR=end_code*units["time_gyr"],
            INITIAL_METALLICITY_ZSUN=args.metallicity, INIT_STELLAR_AGE_MEAN_GYR=age,
            METALLICITY_INITIALIZER="INIT_STELLAR_METALS_AGES_DEFINED + InitMetallicity",
            GIZMO_SHA256=executable["sha256"])
        for key, value in asdict(sat).items():
            meta.attrs[key] = value
        finalize_new_ic(f, args.target_format, raw_units)
    ic_validation = validate_generated_ic(ic)
    param = run / f"{system.lower()}.param"
    overrides = dict(InitCondFile=str(ic), OutputDir=str(run/"output")+"/", ICFormat=3,
        SnapFormat=3, TimeBegin=0, TimeMax=format(end_code, ".16g"), TimeOfFirstSnapshot=0,
        TimeBetSnapshot=format(end_code/6, ".16g"), OutputListOn=0,
        NumFilesPerSnapshot=1, NumFilesWrittenInParallel=1, SnapshotFileBase="snapshot",
        RestartFile="restart", InitGasTemp=0, InitMetallicity=args.metallicity,
        InitStellarAge=age)
    write_param(param, lines, overrides)
    manifest = dict(version=VERSION, system=system, target_format=args.target_format, ic_validation=ic_validation, base_param=str(base),
        base_param_sha256=sha256(base), gizmo=executable, raw_units=raw_units, units=units,
        target_end_code=end_code, target_end_gyr=end_code*units["time_gyr"],
        initial_metallicity_zsun=args.metallicity, initial_stellar_age_mean_gyr=age,
        initial_stellar_age_rule="GIZMO flag0 uniform [0,2*InitStellarAge]; not an observed SFH",
        model=asdict(sat), source_script_sha256=sha256(Path(__file__).with_name("tg19_backend.py")),
        ic=str(ic), ic_sha256=sha256(ic), output_dir=str(run/"output"), seed=args.seed,
        counts=counts, id_bits=args.id_bits, binary_pre_evolution_included=False)
    write_json(run/"relax_manifest.json", manifest)
    run_script(run/"run_relax.sh", executable, param, base.parent, 0, run/"gizmo_run.log", args.mpi_tasks)
    print(f"{system}: 已生成 {ic}\nTimeMax={end_code:.12f} code = {end_code*units['time_gyr']:.7f} Gyr")
    print(f"初始 Z={args.metallicity:g} Zsun；InitStellarAge={age:g} Gyr（均值，非单龄）")
    print(f"counts={counts.tolist()}\n启动: bash {run/'run_relax.sh'}")
    if args.stellar_age_gyr is None and "InitStellarAge" not in values:
        print("提示：base-param 未给恒星年龄，已显式写入代码原默认 10 Gyr；如需其他星族，请生成前设置 --stellar-age-gyr。")


def cli_run(function, *args):
    try:
        function(*args)
    except (ValueError, RuntimeError, OSError, KeyError) as exc:
        print(f"错误: {exc}", file=sys.stderr)
        raise SystemExit(2)
